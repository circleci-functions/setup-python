//go:build acceptance

package setuppython_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gotest.tools/v3/assert"
)

// TestAcceptance_InstallPackages_CacheRoundTrip runs a real install for every
// supported package manager and proves a full save-then-restore round trip
// around it -- against CircleCI's own cache in CI (TOOLKIT_CACHE_MODE=live),
// in-memory on a laptop.
//
// --cache-version is fed the sandbox's per-run nonce so the computed cache key
// is unique to this run. That matters against the live, write-once cache:
// setup-python's key is otherwise derived from the lockfile and would recur
// across pipeline runs, so a re-save would be a no-op leaving an earlier run's
// temp path stored and this run's restore would miss. The nonce makes the key
// fresh every run, so the round trip is exact.
//
// --venv-path pins the cache to a single dir this test controls (VenvPaths
// returns the override outright for any manager, including pip/pip-dist which
// otherwise have no venv), and --pypi-cache=false drops the per-tool pypi paths
// (~/.cache/pip et al) -- their macOS locations ignore XDG_CACHE_HOME, so they
// would not be sandbox-isolated. The real install command still runs for real;
// the marker only proves which path the round trip moved.
func TestAcceptance_InstallPackages_CacheRoundTrip(t *testing.T) {
	// Every fixture under internal/testing/testdata declares zero external
	// dependencies (generated by really running each tool against an empty
	// project), so the real install never reaches the network.
	tests := []struct {
		name       string
		pkgManager string
		fixture    string
		// tool, if set, is required on PATH; the subtest skips when it is
		// absent. pip/pip-dist install via pip3, assumed present with python3.
		tool string
		// extraArgs, appended via --args, keep each real install offline and
		// confined to a scratch --target rather than any shared site-packages.
		// --no-user because a Python setup-python installed may be configured
		// to install for the user, which pip refuses to combine with --target.
		extraArgs func(target string) string
	}{
		{
			name:       "pip",
			pkgManager: "pip",
			fixture:    "pip",
			extraArgs:  func(target string) string { return "--no-user --target " + target },
		},
		{
			name:       "pip-dist",
			pkgManager: "pip-dist",
			fixture:    "pip-dist",
			// --no-build-isolation: without it pip fetches setuptools into an
			// isolated build env over the network, though it is present locally.
			extraArgs: func(target string) string { return "--no-user --no-build-isolation --target " + target },
		},
		{name: "pipenv", pkgManager: "pipenv", fixture: "pipenv", tool: "pipenv"},
		{name: "poetry", pkgManager: "poetry", fixture: "poetry", tool: "poetry"},
		{name: "uv", pkgManager: "uv", fixture: "uv", tool: "uv"},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if tc.tool != "" {
				requireTool(t, tc.tool)
			}

			s, run := sandbox(t)
			appDir := copyFixture(t, tc.fixture)
			scratch := t.TempDir()

			args := []string{
				"install-packages",
				"--app-dir", appDir,
				"--package-manager", tc.pkgManager,
				"--cache-version", s.CacheKeyNonce,
				"--venv-path", scratch,
				"--pypi-cache=false",
			}
			if tc.extraArgs != nil {
				// One "--args=value" token: kong otherwise misparses a value
				// starting with "--" as the next flag.
				args = append(args, "--args="+tc.extraArgs(t.TempDir()))
			}

			marker := filepath.Join(scratch, "marker")
			assert.NilError(t, os.WriteFile(marker, []byte(tc.name+"-cached"), 0600))

			// Run 1: nothing saved under this fresh key, so restore is a no-op;
			// the real install runs; save captures the marker in scratch.
			out, err := run(t, installEnv(), args...)
			assert.NilError(t, err, "run 1 (save) output: %s", out)
			assert.Assert(t, strings.Contains(out, "using package manager "+tc.pkgManager),
				"expected output to report the package manager; got: %s", out)

			assert.NilError(t, os.RemoveAll(scratch))

			// Run 2: restore must repopulate scratch -- including the marker --
			// before the install runs again. Nothing else recreates scratch.
			out, err = run(t, installEnv(), args...)
			assert.NilError(t, err, "run 2 (restore) output: %s", out)

			got, err := os.ReadFile(marker) //nolint:gosec // marker is a test temp file
			assert.NilError(t, err, "expected the marker restored from cache; output: %s", out)
			assert.Equal(t, string(got), tc.name+"-cached")
		})
	}
}
