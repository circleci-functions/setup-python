package setuppython_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"gotest.tools/v3/assert"

	"github.com/circleci/functions/pkg/sdk/sdktest"
)

// TestCLI_InstallPackages_CacheRoundTrip proves, for every supported package
// manager, a full cache-miss-then-cache-hit round trip against a fake
// CircleCI plugin server (pkg/sdk/sdktest):
//
//  1. cache-miss run: nothing is cached yet, so RestoreCache is a no-op; the
//     real package manager installs for real; SaveCache then captures
//     whatever's on disk at the (--venv-path-overridden) cache path -- a
//     marker file this test plants there, proving the path SaveCache walks
//     is the exact one the CLI computed.
//  2. the cache path is wiped, simulating a fresh checkout with nothing
//     locally cached.
//  3. cache-hit run: RestoreCache repopulates the marker (and whatever the
//     real install leaves behind) before the install runs again. The marker
//     reappearing is what proves both halves of the round trip: it can only
//     be back on disk if run 1's save captured it and run 2's restore wrote
//     it out again under the same computed key.
//
// --venv-path overrides the venv cache path to a directory this test fully
// controls (see cache.go's VenvPaths: the override wins outright for any
// manager, including pip/pip-dist which otherwise have no venv), and
// --no-pypi-cache drops the fixed, non-overridable pypi cache paths
// (~/.cache/pip et al) from the round trip entirely. Those pypi paths follow
// each tool's own per-platform conventions (e.g. pip caches under
// ~/Library/Caches/pip on macOS, not the ~/.cache/pip it uses on Linux), so
// pinning the round trip to a single, fully-controlled path keeps the test
// deterministic on every platform, while the real install command still runs
// for real, proving the compiled binary actually drives pip/pipenv/poetry/uv
// end-to-end.
func TestCLI_InstallPackages_CacheRoundTrip(t *testing.T) {
	// One case per supported package manager. Every fixture under testdata/
	// deliberately declares zero external dependencies, and was generated by
	// really running each tool, so that the real pip/pipenv/poetry/uv
	// invocation these tests exercise never touches the network -- these
	// tests must pass hermetically:
	//
	//   - testdata/pip, testdata/pip-dist: requirements.txt generated via
	//     `pip freeze` against a brand-new venv (0 packages installed).
	//   - testdata/pipenv: Pipfile/Pipfile.lock generated via `pipenv lock`
	//     with an empty [packages] table.
	//   - testdata/poetry: pyproject.toml/poetry.lock generated via
	//     `poetry init --no-interaction` + `poetry lock` with package-mode
	//     disabled and zero dependencies.
	//   - testdata/uv: pyproject.toml/uv.lock generated via
	//     `uv init --no-package` + `uv lock` with zero dependencies.
	tests := []struct {
		name string
		// pkgManager is the --pkg-manager value.
		pkgManager string
		// tool, if set, is looked up on PATH and the subtest is skipped when
		// it isn't found (pip/pip-dist have no separate tool binary beyond
		// pip3, which this suite assumes is always present alongside
		// python3).
		tool string
		// fixture is the testdata dir to seed --app-dir from.
		fixture string
		// extraArgs is appended via --args to the install command, keeping
		// each manager's real install hermetic (offline) and confined to
		// scratch directories instead of any shared site-packages.
		extraArgs func(target string) string
	}{
		{
			name:       "pip",
			pkgManager: "pip",
			fixture:    "testdata/pip",
			extraArgs: func(target string) string {
				return "--target " + target
			},
		},
		{
			name:       "pip-dist",
			pkgManager: "pip-dist",
			fixture:    "testdata/pip-dist",
			extraArgs: func(target string) string {
				// --no-build-isolation: without it, pip tries to fetch
				// setuptools into an isolated build env over the network
				// even though it's already available locally.
				return "--no-build-isolation --target " + target
			},
		},
		{
			name:       "pipenv",
			pkgManager: "pipenv",
			tool:       "pipenv",
			fixture:    "testdata/pipenv",
		},
		{
			name:       "poetry",
			pkgManager: "poetry",
			tool:       "poetry",
			fixture:    "testdata/poetry",
		},
		{
			name:       "uv",
			pkgManager: "uv",
			tool:       "uv",
			fixture:    "testdata/uv",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if tc.tool != "" {
				_, err := exec.LookPath(tc.tool)
				if err != nil {
					t.Skipf("%s not found on PATH", tc.tool)
				}
			}

			srv := sdktest.NewServer(t)
			srv.SetupEnv(t)

			appDir := t.TempDir()
			copyFixture(t, tc.fixture, appDir)

			scratchDir := t.TempDir()
			env := map[string]string{
				"HOME":                          t.TempDir(),
				"BASH_ENV":                      filepath.Join(t.TempDir(), "bash_env"),
				"PIP_DISABLE_PIP_VERSION_CHECK": "1",
				// pipenv/poetry create their venvs via the virtualenv
				// package, which otherwise spawns a detached background
				// process to check PyPI for newer bundled seed wheels every
				// 14 days -- a stray network call that can also still be
				// writing into $HOME after this test's own process exits,
				// racing t.TempDir()'s cleanup.
				"VIRTUALENV_NO_PERIODIC_UPDATE": "1",
				// Cleared so the round trip is deterministic regardless of
				// what's set in the host/CI environment running this test.
				"WORKON_HOME":              "",
				"PIPENV_VENV_IN_PROJECT":   "",
				"CIRCLE_WORKING_DIRECTORY": "",
			}

			args := []string{
				"install-packages",
				"--app-dir", appDir,
				"--pkg-manager", tc.pkgManager,
				"--venv-path", scratchDir,
				"--no-pypi-cache",
			}
			if tc.extraArgs != nil {
				// Must be a single "--args=value" token: kong otherwise
				// misparses a value starting with "--" (e.g. "--target ...")
				// as the next flag rather than --args' value.
				args = append(args, "--args="+tc.extraArgs(t.TempDir()))
			}

			marker := filepath.Join(scratchDir, "marker")
			assert.NilError(t, os.WriteFile(marker, []byte(tc.name+"-cached"), 0600))

			// Run 1: cache miss. Nothing has ever been saved under this
			// key, so restore is a no-op; install runs for real; save
			// captures the marker (plus whatever the real install left in
			// scratchDir, if anything).
			out, err := run(t, env, args...)
			assert.NilError(t, err, "run 1 (cache miss) output: %s", out)
			assert.Assert(t, strings.Contains(out, "using package manager "+tc.pkgManager),
				"expected output to report the package manager; got: %s", out)

			assert.NilError(t, os.RemoveAll(scratchDir))

			// Run 2: cache hit. Restore must repopulate scratchDir --
			// including the marker -- before install runs again. Nothing
			// else recreates it: the install command only writes to the
			// fixture's app dir and, where --args sets one, its own separate
			// --target directory.
			out, err = run(t, env, args...)
			assert.NilError(t, err, "run 2 (cache hit) output: %s", out)

			got, err := os.ReadFile(marker) //nolint:gosec // test fixture path
			assert.NilError(t, err, "expected marker file to have been restored from cache; output: %s", out)
			assert.Equal(t, string(got), tc.name+"-cached")
		})
	}
}
